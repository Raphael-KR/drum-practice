// Reflow the approved vector artwork; never substitute its notation glyphs.
import { readFileSync, writeFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';
const source = JSON.parse(readFileSync('src/vendor/score-legend-svg.ts', 'utf8').split('export const scoreLegendSVG = ')[1].trim().slice(0, -1));
const document = new JSDOM(source, { contentType: 'image/svg+xml' }).window.document;
const svg = document.documentElement;
const rows = Array.from(svg.children).filter(e => e.localName === 'g');
const width = 1000;
let rowIndex = 0;
for (const row of rows) {
  const entries = [];
  for (const child of Array.from(row.children)) {
    if (child.localName === 'g' && child.hasAttribute('transform')) entries.push({ glyph: child, labels: [] });
    else if (child.matches('text.name, text.desc')) entries.at(-1).labels.push(child);
  }
  const split = Math.ceil(entries.length / 2);
  for (const part of [entries.slice(0, split), entries.slice(split)]) {
    const next = row.cloneNode(true);
    next.setAttribute('transform', `translate(0 ${16 + rowIndex * 256})`);
    next.id = `legend-portrait-row-${rowIndex++}`;
    const clip = next.querySelector('clipPath');
    const previousId = clip.id;
    clip.id = `${previousId}-${rowIndex}`;
    next.querySelector('[clip-path]').setAttribute('clip-path', `url(#${clip.id})`);
    for (const e of Array.from(next.children)) {
      if ((e.localName === 'g' && e.hasAttribute('transform')) || e.matches('text.name, text.desc')) e.remove();
    }
    // Background panes and staff lines stretch horizontally; glyphs and labels do not.
    const background = document.createElementNS(svg.namespaceURI, 'g');
    background.setAttribute('transform', `scale(${width / 1800} 1)`);
    for (const e of Array.from(next.children)) {
      if (e.localName !== 'text') background.append(e);
    }
    next.prepend(background);
    const heading = next.querySelector(':scope > text');
    heading.setAttribute('x', '24');
    part.forEach((entry, index) => {
      const oldX = Number(entry.labels[0].getAttribute('x'));
      const x = 30 + (index + .5) * (width - 60) / part.length;
      const group = document.createElementNS(svg.namespaceURI, 'g');
      group.setAttribute('transform', `translate(${x - oldX} 0)`);
      group.append(entry.glyph.cloneNode(true));
      next.append(group);
      const name = entry.labels[0].cloneNode(true);
      name.setAttribute('x', String(x));
      next.append(name);
      const descriptions = entry.labels.slice(1).flatMap(e => e.textContent.split(' · '));
      descriptions.forEach((text, line) => {
        const label = entry.labels[1].cloneNode(true);
        label.textContent = text;
        label.setAttribute('x', String(x));
        label.setAttribute('y', String(211 + line * 24));
        next.append(label);
      });
    });
    svg.append(next);
  }
  row.remove();
}
svg.setAttribute('width', String(width));
svg.setAttribute('height', '2080');
svg.setAttribute('viewBox', `0 0 ${width} 2080`);
// Both illustrations coexist in the document; every resource ID must be unique.
let output = svg.outerHTML.replaceAll('legend-', 'portrait-legend-').replaceAll('glass-row-', 'portrait-glass-row-');
output = output.replaceAll('score-portrait-legend-illustration', 'score-legend-illustration');
writeFileSync('src/vendor/score-legend-portrait-svg.ts', '// Generated by scripts/build-portrait-legend.mjs from approved landscape artwork.\nexport const scoreLegendPortraitSVG = ' + JSON.stringify(output) + ';\n');
